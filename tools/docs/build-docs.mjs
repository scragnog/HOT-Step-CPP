#!/usr/bin/env node
// build-docs.mjs — regenerate the tables in the docs that are derived from source.
//
//   node tools/docs/build-docs.mjs            write
//   node tools/docs/build-docs.mjs --check    exit 1 if any output would change (used by check-docs)
//
// Outputs:
//   docs/user/plugins.md          solver / scheduler / guidance / postprocess tables (engine/plugins + plugins/)
//   docs/user/models.md           model registry tables (server/src/data/model-registry.json)
//   docs/dev/api.md               HTTP route index (server/src/index.ts mounts + router.<verb> calls)
//   server/src/data/assistant-knowledge.md   marked blocks refreshed from docs/user
//
// Generated regions are delimited by <!-- generated:start NAME --> … <!-- generated:end NAME -->.
// Hand-written text outside the markers is left alone. Node builtins only.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const CHECK = process.argv.includes('--check');
const rel = (p) => path.relative(ROOT, p).replaceAll('\\', '/');
const read = (p) => fs.readFileSync(p, 'utf8');
const exists = (p) => fs.existsSync(p);
const walk = (dir, filter) =>
  exists(dir)
    ? fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
        const p = path.join(dir, e.name);
        return e.isDirectory() ? walk(p, filter) : filter(p) ? [p] : [];
      })
    : [];
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
const table = (header, rows) =>
  [`| ${header.join(' | ')} |`, `|${header.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(esc).join(' | ')} |`)].join('\n');

let changed = [];
function fill(file, blocks) {
  if (!exists(file)) { console.warn(`[build-docs] missing ${rel(file)}, skipped`); return; }
  let text = read(file);
  for (const [name, body] of Object.entries(blocks)) {
    const re = new RegExp(`(<!-- generated:start ${name} -->)[\\s\\S]*?(<!-- generated:end ${name} -->)`);
    if (!re.test(text)) { console.warn(`[build-docs] ${rel(file)} has no block "${name}"`); continue; }
    text = text.replace(re, `$1\n<!-- generated by tools/docs/build-docs.mjs, do not edit by hand -->\n${body.trim()}\n$2`);
  }
  if (text !== read(file)) {
    changed.push(rel(file));
    if (!CHECK) fs.writeFileSync(file, text);
  }
}

// ── Plugins ──────────────────────────────────────────────────────────────────
// Each plugin declares one Lua table: solver = { name = "...", display = "...", ... }.
function parsePlugin(file) {
  const src = read(file);
  const m = src.match(/^(solver|scheduler|guidance|postprocess)\s*=\s*\{/m);
  if (!m) return null;
  const head = src.slice(m.index, m.index + 2500);
  const field = (k) => head.match(new RegExp(`^\\s*${k}\\s*=\\s*(?:"([^"]*)"|'([^']*)'|([\\w.-]+))`, 'm'))?.slice(1).find((x) => x !== undefined);
  const params = (head.match(/^\s*\{\s*key\s*=\s*"/gm) || []).length;
  return { type: m[1], file, name: field('name') ?? path.basename(file, '.lua'), display: field('display') ?? '', description: field('description') ?? '',
    nfe: field('nfe'), order: field('order'), stochastic: field('stochastic'), stateful: field('stateful'), params };
}
function pluginTables() {
  const sources = [['engine/plugins', 'built in'], ['plugins', 'community']];
  const all = sources.flatMap(([dir, origin]) => walk(path.join(ROOT, dir), (p) => p.endsWith('.lua')).map(parsePlugin).filter(Boolean).map((p) => ({ ...p, origin })));
  const by = (t) => all.filter((p) => p.type === t).sort((a, b) => a.display.localeCompare(b.display) || a.name.localeCompare(b.name));
  const params = (p) => (p.params ? `${p.params}` : '');
  return {
    solvers: table(['Solver', 'Id', 'NFE', 'Order', 'Stochastic', 'Params', 'Description', 'Source'],
      by('solver').map((p) => [p.display, `\`${p.name}\``, p.nfe ?? '', p.order ?? '', p.stochastic === 'true' ? 'yes' : '', params(p), p.description, `${p.origin}, \`${rel(p.file)}\``])),
    schedulers: table(['Scheduler', 'Id', 'Params', 'Description', 'Source'],
      by('scheduler').map((p) => [p.display, `\`${p.name}\``, params(p), p.description, `${p.origin}, \`${rel(p.file)}\``])),
    guidance: table(['Guidance mode', 'Id', 'Params', 'Description', 'Source'],
      by('guidance').map((p) => [p.display, `\`${p.name}\``, params(p), p.description, `${p.origin}, \`${rel(p.file)}\``])),
    postprocess: table(['Post-process plugin', 'Id', 'Params', 'Description', 'Source'],
      by('postprocess').map((p) => [p.display, `\`${p.name}\``, params(p), p.description, `${p.origin}, \`${rel(p.file)}\``])),
  };
}

// ── Models ───────────────────────────────────────────────────────────────────
const gb = (n) => (n ? `${(n / 1e9).toFixed(n < 1e9 ? 2 : 1)} GB` : '');
function modelTables() {
  const reg = JSON.parse(read(path.join(ROOT, 'server/src/data/model-registry.json')));
  const byId = Object.fromEntries(reg.files.map((f) => [f.id, f]));
  const families = [...new Set(reg.files.map((f) => f.family))].sort();
  const out = {
    packs: table(['Pack', 'Family', 'Files', 'Total size', 'Description'],
      reg.packs.map((p) => [p.name, p.family, p.fileIds.length, gb(p.fileIds.reduce((s, id) => s + (byId[id]?.sizeBytes ?? 0), 0)), p.description])),
  };
  for (const fam of families) {
    const files = reg.files.filter((f) => f.family === fam).sort((a, b) => a.role.localeCompare(b.role) || a.filename.localeCompare(b.filename));
    out[`files-${fam}`] = table(['Role', 'Name', 'File', 'Quant', 'Size', 'Repo', 'Description'],
      files.map((f) => [f.role, f.displayName, `\`${f.filename}\``, f.quant ?? '', gb(f.sizeBytes), f.repo ? `[${f.repo}](https://huggingface.co/${f.repo})` : '', f.description]));
  }
  return { out, families };
}

// ── API routes ───────────────────────────────────────────────────────────────
function routeIndex() {
  const index = read(path.join(ROOT, 'server/src/index.ts'));
  const imports = Object.fromEntries([...index.matchAll(/^import (\w+) from '\.\/routes\/(\w+)\.js';/gm)].map((m) => [m[1], m[2]]));
  const mounts = [...index.matchAll(/^app\.use\('([^']+)',\s*(\w+)\);/gm)].map((m) => ({ prefix: m[1], file: imports[m[2]] })).filter((m) => m.file);
  const verbRe = /router\.(get|post|put|delete|patch)\(\s*['"`]([^'"`]*)['"`]/g;
  const routesIn = (file) => [...read(file).matchAll(verbRe)].map((m) => ({ verb: m[1].toUpperCase(), path: m[2] }));
  const sections = mounts.map(({ prefix, file }) => {
    const main = path.join(ROOT, 'server/src/routes', `${file}.ts`);
    const subs = walk(path.join(ROOT, 'server/src/routes', file), (p) => p.endsWith('.ts'));
    const routes = [main, ...subs].flatMap((f) => routesIn(f).map((r) => ({ ...r, file: rel(f) })));
    const rows = routes.map((r) => [`\`${r.verb}\``, `\`${(prefix + (r.path === '/' ? '' : r.path)) || '/'}\``, `\`${r.file}\``]);
    return `### \`${prefix}\`\n\n${table(['Method', 'Path', 'Defined in'], rows)}`;
  });
  return { routes: sections.join('\n\n'), count: sections.reduce((n, s) => n + (s.split('\n').length - 4), 0) };
}

// ── Assistant knowledge base (built from docs/user) ──────────────────────────
function firstParagraph(md) {
  const lines = md.split(/\r?\n/);
  let i = lines.findIndex((l) => /^# /.test(l)) + 1;
  while (i < lines.length && (!lines[i].trim() || lines[i].startsWith('![') || lines[i].startsWith('<!--'))) i++;
  const para = [];
  while (i < lines.length && lines[i].trim() && !lines[i].startsWith('#')) para.push(lines[i++]);
  return para.join(' ').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1');
}
function sectionBody(md, heading) {
  // Body of "## heading" up to the next "## " (links flattened, generator markers dropped).
  const re = new RegExp(`^## ${heading.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*$([\\s\\S]*?)(?=^## |$(?![\\s\\S]))`, 'm');
  return (md.match(re)?.[1] ?? '').replace(/<!--[\s\S]*?-->\n?/g, '').replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').trim();
}
function assistantBlocks(plugins) {
  const studios = walk(path.join(ROOT, 'docs/user/studios'), (p) => p.endsWith('.md'))
    .map((p) => { const md = read(p); return [md.match(/^# (.+)$/m)?.[1] ?? path.basename(p, '.md'), firstParagraph(md)]; })
    .filter(([, para]) => para);
  const troubleshooting = exists(path.join(ROOT, 'docs/user/troubleshooting.md')) ? read(path.join(ROOT, 'docs/user/troubleshooting.md')) : '';
  const backends = exists(path.join(ROOT, 'docs/user/backends.md')) ? read(path.join(ROOT, 'docs/user/backends.md')) : '';
  return {
    studios: studios.map(([name, para]) => `- **${name}**: ${para}`).join('\n'),
    backends: firstParagraph(backends),
    solvers: plugins.solvers, schedulers: plugins.schedulers, guidance: plugins.guidance,
    troubleshooting: sectionBody(troubleshooting, 'Common problems') || firstParagraph(troubleshooting),
  };
}

// ── Run ──────────────────────────────────────────────────────────────────────
const plugins = pluginTables();
fill(path.join(ROOT, 'docs/user/plugins.md'), plugins);

const { out: models, families } = modelTables();
const modelsFile = path.join(ROOT, 'docs/user/models.md');
if (exists(modelsFile)) {
  // Make sure a block exists per family so a new family in the registry appears without a hand edit.
  let text = read(modelsFile);
  for (const fam of families) {
    if (!text.includes(`<!-- generated:start files-${fam} -->`)) {
      text += `\n## Files: ${fam}\n\n<!-- generated:start files-${fam} -->\n<!-- generated:end files-${fam} -->\n`;
      if (!CHECK) fs.writeFileSync(modelsFile, text);
      else changed.push(rel(modelsFile));
    }
  }
  fill(modelsFile, models);
}

const api = routeIndex();
fill(path.join(ROOT, 'docs/dev/api.md'), { routes: api.routes, 'route-count': `${api.count} routes` });

fill(path.join(ROOT, 'server/src/data/assistant-knowledge.md'), assistantBlocks(plugins));

if (CHECK) {
  if (changed.length) { console.error(`[build-docs] stale generated docs, run "node tools/docs/build-docs.mjs":\n  ${changed.join('\n  ')}`); process.exit(1); }
  console.log('[build-docs] generated docs are current');
} else {
  console.log(changed.length ? `[build-docs] updated: ${changed.join(', ')}` : '[build-docs] nothing changed');
}
