// CPU-only checks. Build with C++17, request.cpp and vendor/yyjson/yyjson.c.
#include "../src/guidance/adg-core.h"
#include "../src/retake-noise.h"
#include "../src/adapter-names.h"
#include "../src/request.h"
#include "yyjson.h"
#include <cassert>
#include <cstdio>

int main(int argc, char ** argv) {
    AceRequest req;
    request_init(&req);
    assert(req.retake_variance == 0 && req.retake_seed == -1);
    assert(req.cfg_interval_start == 0 && req.cfg_interval_end == 1);
    assert(request_parse_json(&req, "{\"cfg_interval_start\":1,\"cfg_interval_end\":0,\"retake_variance\":1,\"retake_seed\":4294967295}"));
    assert(req.cfg_interval_start == 1 && req.cfg_interval_end == 0);
    assert(req.retake_variance == 1 && req.retake_seed == 4294967295LL);
    AceRequest roundtrip;
    request_init(&roundtrip);
    assert(request_parse_json(&roundtrip, request_to_json(&req).c_str()));
    assert(roundtrip.retake_seed == req.retake_seed && roundtrip.retake_variance == 1);
    assert(roundtrip.cfg_interval_start == 1 && roundtrip.cfg_interval_end == 0);
    // Each numeric field must guard its own input; JSON integers must work.
    request_init(&req);
    assert(request_parse_json(&req, "{\"cfg_interval_start\":\"bad\",\"cfg_interval_end\":0,\"retake_variance\":-5}"));
    assert(req.cfg_interval_start == 0 && req.cfg_interval_end == 0 && req.retake_variance == 0);
    assert(cfg_in_interval(0.4f, 0.4f, 0.8f));
    assert(cfg_in_interval(0.8f, 0.4f, 0.8f));
    assert(!cfg_in_interval(0.2f, 0.4f, 0.8f));
    assert(!cfg_in_interval(0.6f, 0.8f, 0.4f));

    const float xt[] = {0.2f,-0.8f,0.7f,0.4f,0.9f,0.5f,-0.4f,0.1f};
    const float cond[] = {0.4f,0.1f,-0.2f,0.6f,-0.1f,0.3f,0.5f,-0.2f};
    const float uncond[] = {-0.3f,0.2f,0.1f,-0.4f,0.2f,-0.5f,0.1f,0.4f};
    float out[8];
    // Golden values generated by the local ACE-Step 1.5 base apg_guidance.py
    // adg_forward on CPU, sigma=0.4, scale=4. No GPU or model weights needed.
    const float expected[] = {1.13047528f,0.15358289f,-0.66396570f,1.62406445f,
                              -0.32967001f,1.38186944f,0.91246873f,-0.93578601f};
    adg_forward(xt, cond, uncond, 4, 0.4f, out, 4, 2);
    for (int i=0;i<8;i++) {
        assert(std::isfinite(out[i]));
        assert(std::abs(out[i]-expected[i]) < 3e-5f);
    }
    for (float sigma : {0.0f, 0.00005f}) {
        adg_forward(xt, cond, uncond, 4, sigma, out, 4, 2);
        for(int i=0;i<8;i++) assert(out[i] == uncond[i]+4*(cond[i]-uncond[i]));
    }
    float zeros[8] = {};
    adg_forward(zeros, zeros, zeros, 4, 0.4f, out, 4, 2);
    for(float v : out) assert(v == 0);

    std::vector<float> original(1024), mixed(1024), other(1024), repeat(1024);
    philox_randn(42, original.data(), 1024, true);
    philox_randn(99, other.data(), 1024, true);
    mixed = original;
    retake_noise(mixed.data(), 1024, 99, 0);
    assert(mixed == original);
    retake_noise(mixed.data(), 1024, 99, 1);
    assert(mixed == other);
    mixed = repeat = original;
    retake_noise(mixed.data(), 1024, 99, 0.5f);
    retake_noise(repeat.data(), 1024, 99, 0.5f);
    assert(mixed == repeat && mixed != original && mixed != other);
    for(int i=0;i<1024;i++) assert(std::abs(mixed[i]-(original[i]+other[i])*std::sqrt(0.5f)) < 1e-6f);

    for(const char * prefix : {"", "base_model.model.", "base_model.model.base_model.model.", "diffusion_model.base_model.model."}) {
        assert(lora_base_name(std::string(prefix)+"layers.0.self_attn.q_proj.lora_A.weight") == "decoder.layers.0.self_attn.q_proj.weight");
    }
    assert(lora_base_name("not-an-adapter").empty());
    yyjson_doc * keys = yyjson_read_file(argc > 1 ? argv[1] : "engine/tests/fixtures/peft-wrapped-keys.json", 0, nullptr, nullptr);
    assert(keys);
    size_t index, count;
    yyjson_val * entry;
    yyjson_arr_foreach(yyjson_doc_get_root(keys), index, count, entry) {
        const char * key = yyjson_get_str(yyjson_obj_get(entry, "key"));
        const char * expected_name = yyjson_get_str(yyjson_obj_get(entry, "expected"));
        assert(key && expected_name && lora_base_name(key) == expected_name);
    }
    yyjson_doc_free(keys);
    std::puts("ACE PARITY PASS: request roundtrip, interval edges, ADG reference, retake endpoints/determinism, repeated PEFT prefixes");
}
