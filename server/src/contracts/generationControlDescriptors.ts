type CoreParamMetadata = Omit<CoreGenerationParamDescriptor, 'key' | 'default'>;
type PluginParamMetadata = Pick<PluginParamSchema, 'label' | 'hint' | 'min' | 'max' | 'step' | 'options'> & {
  type: PluginParamSchema['type'] | 'array' | 'object';
};

const slider = (label: string, min?: number, max?: number, step?: number, hint?: string): CoreParamMetadata =>
  ({ type: 'slider', label, min, max, step, hint });

const toggle = (label: string, hint?: string): CoreParamMetadata => ({ type: 'toggle', label, hint });
const text = (label: string, hint?: string): CoreParamMetadata => ({ type: 'text', label, hint });
const select = (label: string, choices?: Record<string, string>, hint?: string): CoreParamMetadata => ({
  type: 'select',
  label,
  options: choices && Object.entries(choices).map(([value, label]) => ({ value, label })),
  hint,
});

